#!/usr/local/bin/python3
"""
rule_tool.py - mosdns rule file management and domain test simulator.

Usage:
  rule_tool.py list
  rule_tool.py get <name>
  rule_tool.py set <name>   (reads content from stdin)
  rule_tool.py test <domain>

Rule files live in /usr/local/etc/mosdns/rule/.
Editable: custom_direct/proxy/block.txt (local groups) and
sync_direct/proxy/block.txt (remote groups)
All six files are generated by merging rule groups (custom_* from
local groups, sync_* from remote groups).
"""
import sys
import os
import json
import re

RULE_DIR = '/usr/local/etc/mosdns/rule'
EDITABLE = {'custom_direct.txt', 'custom_proxy.txt', 'custom_block.txt',
            'sync_direct.txt', 'sync_proxy.txt', 'sync_block.txt'}
ALL_FILES = ['custom_direct.txt', 'custom_proxy.txt', 'custom_block.txt',
             'sync_direct.txt', 'sync_proxy.txt', 'sync_block.txt']


def load_rules(path):
    rules = []
    try:
        with open(path) as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith('#'):
                    continue
                rules.append(line)
    except OSError:
        pass
    return rules


def match_domain(domain, rules):
    """Return (matched_rule, kind) or (None, None). kind: full/domain."""
    domain = domain.lower().strip()
    # strip scheme/path/port
    for prefix in ('https://', 'http://'):
        if domain.startswith(prefix):
            domain = domain[len(prefix):]
    domain = domain.split('/')[0].split(':')[0]
    for rule in rules:
        r = rule.lower()
        if r.startswith('regexp:'):
            try:
                if re.search(rule[7:], domain):
                    return rule, 'regexp'
            except re.error:
                pass
            continue
        if r.startswith('full:'):
            if domain == r[5:]:
                return rule, 'full'
        elif r.startswith('domain:'):
            pat = r[7:]
            if domain == pat or domain.endswith('.' + pat):
                return rule, 'domain'
        else:
            # bare domain = suffix match
            if domain == r or domain.endswith('.' + r):
                return rule, 'domain'
    return None, None


def cmd_list():
    result = []
    for name in ALL_FILES:
        path = os.path.join(RULE_DIR, name)
        rules = load_rules(path)
        try:
            st = os.stat(path)
            mtime, size = int(st.st_mtime), st.st_size
        except OSError:
            mtime, size = 0, 0
        result.append({
            'name': name,
            'editable': name in EDITABLE,
            'count': len(rules),
            'mtime': mtime,
            'size': size,
        })
    print(json.dumps(result))


def cmd_get(name):
    if name not in ALL_FILES:
        print(f'unknown file: {name}', file=sys.stderr)
        sys.exit(1)
    path = os.path.join(RULE_DIR, name)
    try:
        with open(path) as f:
            sys.stdout.write(f.read())
    except OSError as e:
        print(f'cannot read: {e}', file=sys.stderr)
        sys.exit(1)


def cmd_install(name, staging):
    """Install a rule file from a staging path (written by the PHP API)."""
    if name not in EDITABLE:
        print(f'file is read-only: {name}', file=sys.stderr)
        sys.exit(1)
    # staging must be under /tmp to avoid path tricks
    staging = os.path.abspath(staging)
    if not staging.startswith('/tmp/'):
        print('staging path must be under /tmp', file=sys.stderr)
        sys.exit(1)
    with open(staging) as f:
        content = f.read()
    # validate before touching the live file: a bad rule file can break mosdns startup
    errors = validate_content(content)
    if errors:
        print(json.dumps({'result': 'failed', 'errors': errors}, ensure_ascii=False))
        sys.exit(1)
    # normalize: LF, strip blank lines
    lines = []
    for line in content.replace('\r\n', '\n').split('\n'):
        line = line.strip()
        if line:
            lines.append(line)
    path = os.path.join(RULE_DIR, name)
    os.makedirs(RULE_DIR, exist_ok=True)
    with open(path, 'w') as f:
        f.write('\n'.join(lines) + '\n' if lines else '')
    os.unlink(staging)
    print('OK')


# domain label: 1-63 chars, alnum + hyphen, not leading/trailing hyphen
_LABEL_RE = r'[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?'
_DOMAIN_RE = re.compile(rf'^{_LABEL_RE}(?:\.{_LABEL_RE})+$', re.IGNORECASE)


def validate_rule(line, lineno):
    """Return an error string for an invalid rule line, or None if OK."""
    s = line.strip()
    if not s or s.startswith('#'):
        return None
    low = s.lower()
    if low.startswith('regexp:'):
        # mosdns' domain matcher supports regexp natively; just make sure
        # the pattern compiles (lists like Loyalsoldier's ship a few).
        pat = s[7:]
        if not pat or len(pat) > 512:
            return f'line {lineno}: empty or overlong regexp'
        try:
            re.compile(pat)
        except re.error as e:
            return f'line {lineno}: invalid regexp: {e}'
        return None
    if low.startswith('full:'):
        dom, kind = s[5:], 'full'
    elif low.startswith('domain:'):
        dom, kind = s[7:], 'domain'
    else:
        dom, kind = s, 'domain'  # bare domain = suffix match (single-label
        # TLD entries like 'cn' are unsupported: far too broad, dropped)
    if not dom:
        return f'line {lineno}: empty domain'
    if '://' in s or '/' in dom:
        return f'line {lineno}: must not contain scheme or path: {s}'
    if ':' in dom:
        return f'line {lineno}: must not contain port: {s}'
    if ' ' in dom or '\t' in dom:
        return f'line {lineno}: must not contain whitespace: {s}'
    if not _DOMAIN_RE.match(dom):
        return f'line {lineno}: invalid domain "{dom}"'
    return None


def validate_content(content):
    """Validate full file content. Returns list of error strings (empty = valid)."""
    errors = []
    for i, line in enumerate(content.replace('\r\n', '\n').split('\n'), 1):
        err = validate_rule(line, i)
        if err:
            errors.append(err)
    return errors


def sanitize_content(content):
    """Drop lines outside the supported rule format (for REMOTE lists:
    upstream lists are third-party data, a few bad lines must not reject
    the whole file -- and must never reach mosdns, which exits on a bad
    rule line). Returns (cleaned_content, dropped_lines). Comments and
    blank lines are kept (inert); local group content is NOT sanitized,
    it stays strictly validated so typos surface as errors."""
    kept, dropped, converted = [], [], []
    for line in content.replace('\r\n', '\n').split('\n'):
        t = line.strip()
        if not t or t.startswith('#'):
            if t:
                kept.append(t)
            continue
        if t.startswith('*.') and validate_rule('domain:' + t[2:], 0) is None:
            # wildcard is exactly a suffix match: *.wild.com == domain:wild.com
            kept.append('domain:' + t[2:])
            converted.append(t)
            continue
        if validate_rule(t, 0) is None:
            kept.append(t)
        else:
            dropped.append(t)
    return ('\n'.join(kept) + ('\n' if kept else '')), dropped, converted


def cmd_validate():
    """Read content from stdin, print validation result as JSON."""
    content = sys.stdin.read()
    errors = validate_content(content)
    if errors:
        print(json.dumps({'result': 'failed', 'errors': errors}, ensure_ascii=False))
        sys.exit(1)
    print(json.dumps({'result': 'ok', 'errors': []}))


# ---------------------------------------------------------------------------
# Rule groups: the canonical store. Each group is a plain-txt domain list
# (bare / domain: / full:, '#' comments) with metadata (name, type, tags,
# source, enabled) kept in the OPNsense model and passed in as a manifest.
#   local group content : rule/groups/<uuid>.txt
#   remote group cache  : rule/groups/<uuid>.cache.txt  (last good fetch)
# mosdns merges local groups into custom_*.txt and remote groups into
# sync_*.txt (this file). Custom files outrank sync files in the config
# sequence, so local rules can override stale or ill-fitting remote lists.
# Rule groups are a mosdns-only, coarse-grained facility: they only
# decide direct/proxy/block at DNS level.
# ---------------------------------------------------------------------------

GROUPS_DIR = os.path.join(RULE_DIR, 'groups')
MANIFEST_OUT = os.path.join(RULE_DIR, 'groups.json')
GROUP_TARGETS = {('local', 'direct'): 'custom_direct.txt',
                 ('local', 'proxy'): 'custom_proxy.txt',
                 ('local', 'block'): 'custom_block.txt',
                 ('remote', 'direct'): 'sync_direct.txt',
                 ('remote', 'proxy'): 'sync_proxy.txt',
                 ('remote', 'block'): 'sync_block.txt'}
GENERATED_MARK = '由 os-mosdns 规则组合并生成'
_UUID_RE = re.compile(r'^[A-Za-z0-9-]{1,64}$')


def group_paths(uuid):
    if not _UUID_RE.match(uuid or ''):
        raise ValueError(f'bad group uuid: {uuid!r}')
    return (os.path.join(GROUPS_DIR, uuid + '.txt'),
            os.path.join(GROUPS_DIR, uuid + '.cache.txt'))


def group_content_path(entry):
    local_p, cache_p = group_paths(entry['uuid'])
    return cache_p if entry.get('source') == 'remote' else local_p


def read_text(path):
    try:
        with open(path) as f:
            return f.read()
    except OSError:
        return None


def count_rules(content):
    if not content:
        return 0
    return sum(1 for ln in content.splitlines()
               if ln.strip() and not ln.strip().startswith('#'))


def cmd_get_group(uuid, source):
    local_p, cache_p = group_paths(uuid)
    path = cache_p if source == 'remote' else local_p
    content = read_text(path)
    try:
        mtime = int(os.stat(path).st_mtime)
    except OSError:
        mtime = 0
    print(json.dumps({'result': 'ok', 'exists': content is not None,
                      'content': content or '', 'mtime': mtime,
                      'count': count_rules(content)}, ensure_ascii=False))


def cmd_install_group(uuid, staging):
    """Install a local group's content from a staging file (validated first)."""
    local_p, _ = group_paths(uuid)
    staging = os.path.abspath(staging)
    if not staging.startswith('/tmp/'):
        print('staging path must be under /tmp', file=sys.stderr)
        sys.exit(1)
    with open(staging) as f:
        content = f.read()
    errors = validate_content(content)
    if errors:
        print(json.dumps({'result': 'failed', 'errors': errors}, ensure_ascii=False))
        sys.exit(1)
    os.makedirs(GROUPS_DIR, exist_ok=True)
    with open(local_p, 'w') as f:
        f.write(content.replace('\r\n', '\n'))
    os.unlink(staging)
    print('OK')


def cmd_fetch_group(uuid, url):
    """Fetch a remote group's txt into its cache. Never clobbers a good
    cache with a failed or invalid download."""
    import urllib.request
    _, cache_p = group_paths(uuid)
    if not (url.startswith('https://') or url.startswith('http://')):
        print(json.dumps({'result': 'failed', 'error': 'url must be http(s)'}, ensure_ascii=False))
        sys.exit(1)
    try:
        req = urllib.request.Request(url, headers={'User-Agent': 'os-mosdns rule fetcher'})
        with urllib.request.urlopen(req, timeout=20) as resp:
            raw = resp.read(8 * 1024 * 1024 + 1)
        if len(raw) > 8 * 1024 * 1024:
            raise ValueError('file too large (>8MB)')
        content = raw.decode('utf-8', 'replace')
    except Exception as e:
        print(json.dumps({'result': 'failed', 'error': f'fetch failed: {e}'}, ensure_ascii=False))
        sys.exit(1)
    cleaned, dropped, converted = sanitize_content(content)
    if count_rules(cleaned) == 0:
        print(json.dumps({'result': 'failed',
                          'error': 'no valid rules after dropping unsupported lines',
                          'dropped': len(dropped)}, ensure_ascii=False))
        sys.exit(1)
    os.makedirs(GROUPS_DIR, exist_ok=True)
    with open(cache_p, 'w') as f:
        f.write(cleaned)
    print(json.dumps({'result': 'ok', 'count': count_rules(cleaned),
                      'dropped': len(dropped), 'dropped_sample': dropped[:5],
                      'converted': len(converted)},
                     ensure_ascii=False))


def cmd_delete_group(uuid):
    for p in group_paths(uuid):
        try:
            os.unlink(p)
        except OSError:
            pass
    print('OK')


def load_manifest(staging):
    staging = os.path.abspath(staging)
    if not staging.startswith('/tmp/'):
        print('staging path must be under /tmp', file=sys.stderr)
        sys.exit(1)
    with open(staging) as f:
        manifest = json.load(f)
    os.unlink(staging)
    if not isinstance(manifest, list):
        print('manifest must be a list', file=sys.stderr)
        sys.exit(1)
    return manifest


def export_manifest(manifest):
    """Write rule/groups.json: the exported index of the group store."""
    import time
    groups = []
    for g in manifest:
        path = group_content_path(g)
        content = read_text(path)
        groups.append({
            'uuid': g.get('uuid', ''),
            'name': g.get('name', ''),
            'type': g.get('type', 'direct'),
            'tags': [t.strip() for t in (g.get('tags') or '').split(',') if t.strip()],
            'source': g.get('source', 'local'),
            'url': g.get('url', ''),
            'enabled': g.get('enabled') in ('1', 1, True),
            'file': os.path.relpath(path, RULE_DIR),
            'count': count_rules(content),
        })
    data = {'version': 1, 'generated': int(time.time()), 'groups': groups}
    os.makedirs(RULE_DIR, exist_ok=True)
    tmp = MANIFEST_OUT + '.tmp'
    with open(tmp, 'w') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    os.replace(tmp, MANIFEST_OUT)
    return data


def _hdr(text):
    return (text or '').replace('\r', ' ').replace('\n', ' ').strip()


def cmd_merge(staging):
    """Merge all enabled groups into the custom_*.txt (local) and
    sync_*.txt (remote) files the mosdns config references, and refresh
    the exported groups.json."""
    import time
    manifest = load_manifest(staging)
    export_manifest(manifest)
    warnings = []
    summary = {}
    stamp = time.strftime('%Y-%m-%d %H:%M:%S')
    for (gsource, gtype), target_name in GROUP_TARGETS.items():
        parts = [f'# {GENERATED_MARK}（{stamp}），请在「规则」页改组内容，不要手工编辑本文件\n']
        seen = set()
        total = 0
        used = []
        for g in manifest:
            if g.get('type') != gtype or (g.get('source') or 'local') != gsource \
                    or g.get('enabled') not in ('1', 1, True):
                continue
            name = _hdr(g.get('name')) or g.get('uuid', '')
            path = group_content_path(g)
            content = read_text(path)
            if content is None:
                kind = '在线缓存不存在（尚未拉取）' if g.get('source') == 'remote' else '本地文件不存在'
                warnings.append(f'组「{name}」跳过：{kind}')
                continue
            errors = validate_content(content)
            if errors:
                if gsource == 'remote':
                    content, dropped, converted = sanitize_content(content)
                    notes = []
                    if dropped:
                        notes.append(f'移除了 {len(dropped)} 条不支持的行')
                    if converted:
                        notes.append(f'转换了 {len(converted)} 条通配符为 domain:')
                    if notes:
                        warnings.append(f'组「{name}」' + '，'.join(notes))
                    if count_rules(content) == 0:
                        warnings.append(f'组「{name}」跳过：清洗后无有效规则')
                        continue
                else:
                    warnings.append(f'组「{name}」跳过：内容校验失败（{errors[0]}）')
                    continue
            tags = _hdr(g.get('tags'))
            parts.append(f'# ===== {name} [{gtype}/{g.get("source", "local")}]'
                         + (f' tags: {tags}' if tags else '') + ' =====\n')
            for line in content.replace('\r\n', '\n').split('\n'):
                s = line.strip()
                if not s:
                    continue
                if s.startswith('#'):
                    parts.append(line.rstrip() + '\n')
                    continue
                if s in seen:
                    continue
                seen.add(s)
                total += 1
                parts.append(s + '\n')
            used.append(name)
        target = os.path.join(RULE_DIR, target_name)
        # safeguard: keep a one-time backup of a hand-written pre-group file
        old = read_text(target)
        if old and GENERATED_MARK not in old and count_rules(old) > 0:
            bak = target + '.bak'
            if not os.path.exists(bak):
                with open(bak, 'w') as f:
                    f.write(old)
                warnings.append(f'{target_name} 原有手工内容已备份到 {target_name}.bak')
        os.makedirs(RULE_DIR, exist_ok=True)
        tmp = target + '.tmp'
        with open(tmp, 'w') as f:
            f.writelines(parts)
        os.replace(tmp, target)
        summary[target_name[:-4]] = {'file': target_name, 'count': total, 'groups': used}
    print(json.dumps({'result': 'ok', 'files': summary, 'warnings': warnings},
                     ensure_ascii=False))


def cmd_export(staging):
    manifest = load_manifest(staging)
    export_manifest(manifest)
    print('OK')


def cmd_test(domain):
    # load config mode from a JSON file dumped by template (or defaults)
    mode = 'whitelist'
    fallback = 'proxy'
    block_enabled = True
    cfg_path = '/usr/local/etc/mosdns/mode.json'
    try:
        with open(cfg_path) as f:
            cfg = json.load(f)
            mode = cfg.get('mode', mode)
            fallback = cfg.get('custom_default_route', fallback)
            block_enabled = cfg.get('block_enabled', '1') == '1'
    except OSError:
        pass

    def _load(name):
        return load_rules(os.path.join(RULE_DIR, name))

    c_direct, c_proxy, c_block = _load('custom_direct.txt'), _load('custom_proxy.txt'), _load('custom_block.txt')
    s_direct, s_proxy, s_block = _load('sync_direct.txt'), _load('sync_proxy.txt'), _load('sync_block.txt')

    result = {'domain': domain, 'mode': mode}

    def _hit(rules, fname, action, explain, sync_pf=False):
        m, kind = match_domain(domain, rules)
        if not m:
            return False
        result.update({'action': action, 'matched_file': fname,
                       'matched_rule': m, 'explain': explain.format(kind=kind)})
        if sync_pf:
            result['sync_pf'] = True
        print(json.dumps(result, ensure_ascii=False))
        return True

    # priority: custom block > custom direct > custom proxy (pf alias) >
    #           sync block > mode over sync direct/proxy > mode default
    if block_enabled and _hit(c_block, 'custom_block.txt', 'block', '命中自定义阻止 ({kind}匹配)，直接拒绝'):
        return
    if _hit(c_direct, 'custom_direct.txt', 'direct', '命中自定义直连 ({kind}匹配)，走本地上游'):
        return
    if _hit(c_proxy, 'custom_proxy.txt', 'proxy', '命中自定义代理 ({kind}匹配)，走远端代理并同步到 pf 表', sync_pf=True):
        return
    if block_enabled and _hit(s_block, 'sync_block.txt', 'block', '命中同步阻止 ({kind}匹配)，直接拒绝'):
        return

    dm, dkind = match_domain(domain, s_direct)
    pm, pkind = match_domain(domain, s_proxy)

    if mode == 'whitelist':
        if dm:
            result.update({'action': 'direct', 'matched_file': 'sync_direct.txt',
                           'matched_rule': dm, 'explain': f'命中同步直连名单 ({dkind}匹配)，走本地上游'})
        else:
            result.update({'action': 'proxy', 'matched_file': None,
                           'matched_rule': None, 'sync_pf': True,
                           'explain': '白名单模式：未命中同步直连名单，走远端代理并同步到 pf 表'})
    elif mode == 'blacklist':
        if pm:
            result.update({'action': 'proxy', 'matched_file': 'sync_proxy.txt',
                           'matched_rule': pm, 'sync_pf': True,
                           'explain': f'命中同步代理名单 ({pkind}匹配)，走远端代理并同步到 pf 表'})
        else:
            result.update({'action': 'direct', 'matched_file': None,
                           'matched_rule': None,
                           'explain': '黑名单模式：未命中同步代理名单，走本地上游'})
    else:  # custom
        if dm:
            result.update({'action': 'direct', 'matched_file': 'sync_direct.txt',
                           'matched_rule': dm, 'explain': f'命中同步直连名单 ({dkind}匹配)，走本地上游'})
        elif pm:
            result.update({'action': 'proxy', 'matched_file': 'sync_proxy.txt',
                           'matched_rule': pm, 'sync_pf': True,
                           'explain': f'命中同步代理名单 ({pkind}匹配)，走远端代理并同步到 pf 表'})
        else:
            fb = fallback
            result.update({'action': fb, 'matched_file': None, 'matched_rule': None,
                           'sync_pf': fb == 'proxy',
                           'explain': f'混合模式：未命中任何名单，按兜底走{"远端代理" if fb == "proxy" else "本地上游"}'})
    print(json.dumps(result, ensure_ascii=False))


def main():
    if len(sys.argv) < 2:
        print('usage: rule_tool.py list|get|set|test ...', file=sys.stderr)
        sys.exit(2)
    cmd = sys.argv[1]
    if cmd == 'list':
        cmd_list()
    elif cmd == 'get' and len(sys.argv) == 3:
        cmd_get(sys.argv[2])
    elif cmd == 'install' and len(sys.argv) == 4:
        cmd_install(sys.argv[2], sys.argv[3])
    elif cmd == 'get_group' and len(sys.argv) == 4:
        cmd_get_group(sys.argv[2], sys.argv[3])
    elif cmd == 'install_group' and len(sys.argv) == 4:
        cmd_install_group(sys.argv[2], sys.argv[3])
    elif cmd == 'fetch_group' and len(sys.argv) == 4:
        cmd_fetch_group(sys.argv[2], sys.argv[3])
    elif cmd == 'delete_group' and len(sys.argv) == 3:
        cmd_delete_group(sys.argv[2])
    elif cmd == 'merge' and len(sys.argv) == 3:
        cmd_merge(sys.argv[2])
    elif cmd == 'export' and len(sys.argv) == 3:
        cmd_export(sys.argv[2])
    elif cmd == 'validate':
        cmd_validate()
    elif cmd == 'test' and len(sys.argv) == 3:
        cmd_test(sys.argv[2])
    else:
        print('bad arguments', file=sys.stderr)
        sys.exit(2)


if __name__ == '__main__':
    main()
